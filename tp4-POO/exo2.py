from Fraction import *

# equal
a = Fraction(23,14)
b = Fraction(46,28) 

# not equal
c = Fraction(11,3)
d = Fraction(18,45)

# +
print(a+b)

# -
print(c-d)

# *
print(a*b)

# /
print(c/d)

# >
print(a>b)

# <
print(a<c)

# >=
print(c>=d)

# <=
print(c<=d)

# ==
print(a==b)
print(c==d)

# !=
print(a!=b)
print(c!=d)